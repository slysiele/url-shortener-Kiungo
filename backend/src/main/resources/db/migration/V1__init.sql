-- Kiungo initial schema. Written to run on both PostgreSQL and H2 (PostgreSQL mode).

CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(255) NOT NULL UNIQUE,
    password_hash   VARCHAR(255) NOT NULL,
    name            VARCHAR(120),
    role            VARCHAR(20)  NOT NULL DEFAULT 'USER',
    plan            VARCHAR(20)  NOT NULL DEFAULT 'FREE',
    trial_ends_at   TIMESTAMP WITH TIME ZONE,
    plan_renews_at  TIMESTAMP WITH TIME ZONE,
    theme           VARCHAR(30),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE links (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT        NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    slug          VARCHAR(64)   NOT NULL UNIQUE,
    original_url  VARCHAR(2048) NOT NULL,
    title         VARCHAR(255),
    tags          VARCHAR(500),
    ios_url       VARCHAR(2048),
    android_url   VARCHAR(2048),
    expires_at    TIMESTAMP WITH TIME ZONE,
    max_clicks    BIGINT,
    click_count   BIGINT        NOT NULL DEFAULT 0,
    active        BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_links_user_created ON links(user_id, created_at);

CREATE TABLE clicks (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    link_id          BIGINT       NOT NULL REFERENCES links(id) ON DELETE CASCADE,
    user_id          BIGINT       NOT NULL,
    clicked_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    ip_hash          VARCHAR(64),
    country          VARCHAR(64),
    city             VARCHAR(120),
    referrer         VARCHAR(1024),
    referrer_domain  VARCHAR(255),
    browser          VARCHAR(80),
    os               VARCHAR(80),
    device           VARCHAR(20),
    bot              BOOLEAN      NOT NULL DEFAULT FALSE,
    utm_source       VARCHAR(255),
    utm_medium       VARCHAR(255),
    utm_campaign     VARCHAR(255)
);
CREATE INDEX idx_clicks_user_time ON clicks(user_id, clicked_at);
CREATE INDEX idx_clicks_link_time ON clicks(link_id, clicked_at);

CREATE TABLE api_keys (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name          VARCHAR(120) NOT NULL,
    prefix        VARCHAR(16)  NOT NULL,
    key_hash      VARCHAR(64)  NOT NULL UNIQUE,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    last_used_at  TIMESTAMP WITH TIME ZONE,
    expires_at    TIMESTAMP WITH TIME ZONE,
    revoked       BOOLEAN      NOT NULL DEFAULT FALSE
);
